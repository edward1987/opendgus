"""The project's VP addresses, pages and power settings for the MCU, as a C header or a Python module."""
from __future__ import annotations

import re

from ..model import Project


def ident(s: str) -> str:
    s = re.sub(r"[^A-Za-z0-9]+", "_", s).strip("_").upper()
    return s if s and not s[0].isdigit() else f"P{s}"


def pages(project: Project) -> list[tuple[str, int]]:
    """(NAME, id) for every user page; screensaver animation frames are left out, duplicate names numbered."""
    skip = set(project.screensaver.frame_pages)
    out, seen = [], set()
    for p in sorted(project.pages, key=lambda p: p.id):
        if p.id in skip:
            continue
        name = ident(p.name or str(p.id))
        if name in seen:
            name = f"{name}_{p.id}"
        seen.add(name)
        out.append((name, p.id))
    return out


def home_page(project: Project) -> int:
    ss = project.screensaver
    ids = [p.id for p in project.pages if p.id != ss.page and p.id not in ss.frame_pages]
    return min(ids, default=0)


def settings(project: Project) -> list[tuple[str, int, str]]:
    """(NAME, value, comment) constants the controller library uses."""
    d, sb, ss = project.display, project.display.standby, project.screensaver
    on = ss.enabled and ss.page is not None
    return [
        ("DGUS_BAUD", d.baud, "display UART baud rate"),
        ("DGUS_CRC", int(d.uart_crc), "1 = frames carry a CRC16"),
        ("DGUS_HOME_PAGE", home_page(project), "first page"),
        ("DGUS_BACKLIGHT", d.backlight, "normal backlight %"),
        ("DGUS_STANDBY_ENABLED", int(sb.enabled), "display dims itself when idle"),
        ("DGUS_STANDBY_LEVEL", sb.level, "idle backlight %"),
        ("DGUS_STANDBY_TIMEOUT_S", sb.timeout_s, "seconds without a touch before dimming"),
        ("SCREENSAVER_ENABLED", int(on), "the controller shows SCREENSAVER_PAGE when idle"),
        ("SCREENSAVER_PAGE", ss.page if on else -1, ""),
        ("SCREENSAVER_TIMEOUT_S", ss.timeout_s, "seconds without a touch"),
        ("SCREENSAVER_WAKE_PAGE", ss.wake_page if ss.wake_page is not None else -1, "-1 = back to the previous page"),
        ("SCREENSAVER_BRIGHTNESS", ss.brightness if ss.brightness is not None else -1, "-1 = unchanged"),
    ]


def _var_comment(v) -> str:
    return f"{v.type}{', x10^-' + str(v.decimals) if v.decimals else ''}{', ' + v.doc if v.doc else ''}"


def c_header(project: Project, vps: dict[str, int]) -> str:
    lines = ["/* Generated by OpenDGUS - DGUS variable (VP) addresses for your MCU. */",
             f"/* Project: {project.name} - {project.display.width}x{project.display.height} */",
             "#pragma once", ""]
    for v in project.variables:
        lines.append(f"#define {'VP_' + v.name.upper():<28} 0x{vps[v.name]:04X}  /* {_var_comment(v)} */")
    lines.append("")
    lines += [f"#define {'PAGE_' + n:<28} {i}" for n, i in pages(project)]
    lines.append("")
    for n, val, doc in settings(project):
        lines.append(f"#define {n:<28} {val}" + (f"  /* {doc} */" if doc else ""))
    return "\n".join(lines) + "\n"


def py_module(project: Project, vps: dict[str, int]) -> str:
    lines = ['"""Generated by OpenDGUS - DGUS variable (VP) addresses for your controller."""',
             f"# Project: {project.name} - {project.display.width}x{project.display.height}", ""]
    for v in project.variables:
        lines.append(f"{'VP_' + v.name.upper():<28} = 0x{vps[v.name]:04X}  # {_var_comment(v)}")
    lines.append("")
    lines += [f"{'PAGE_' + n:<28} = {i}" for n, i in pages(project)]
    lines.append("")
    for n, val, doc in settings(project):
        lines.append(f"{n:<28} = {val}" + (f"  # {doc}" if doc else ""))
    return "\n".join(lines) + "\n"
