"""Generate a controller project (Arduino sketch, MicroPython or Python) for an OpenDGUS project.

    files = generate(project, "nano")                  # {relative path: text}
    write(project_folder, project, "nano")             # -> <folder>/controller/nano/..., keeps USER CODE blocks

Code between `USER CODE BEGIN <name>` and `USER CODE END <name>` markers is yours: regenerating keeps it, so you
(or the AI) can change the design and regenerate without losing the logic.
"""
