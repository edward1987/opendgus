# ====================================================================== entry points

def main_file(project: Project, board: str) -> str:
    """Path of the main source file inside the controller folder."""
    b = get_board(board)
    if b.lang == "arduino":
        sk = sketch_name(project)
        return f"{sk}/{sk}.ino"
    return "main.py"


def generate(project: Project, board: str, mqtt: bool = False, logic: Optional[dict[str, str]] = None) -> dict[str, str]:
    """Files of the controller project, relative to <project>/controller/<board>/ (no merge with old files)."""
    b = get_board(board)
    if mqtt and not b.wifi:
        raise ValueError(f"{b.title} has no network; MQTT needs a Pico 2 W, an ESP32, a Raspberry Pi or a PC")
    vs = variables(project)
    vps = project.allocate_vps()
    logic = logic or {}
    out: dict[str, str] = {}
    main = main_file(project, board)
    if b.lang == "arduino":
        sk = sketch_name(project)
        out[main] = _cpp_main(project, b, vs, mqtt, logic)
        out[f"{sk}/vars.h"] = A.c_header(project, vps)
        lib = DATA / "arduino" / "OpenDGUS"
        for f in ("src/OpenDGUS.h", "src/OpenDGUS.cpp"):
            out[f"{sk}/src/OpenDGUS/{Path(f).name}"] = (lib / f).read_text(encoding="utf-8")
        if mqtt:
            out[f"{sk}/secrets.h"] = _secrets_h(project)
    else:
        out[main] = _py_main(project, b, vs, mqtt, logic)
        out["dgus_vars.py"] = A.py_module(project, vps)
        out["opendgus.py"] = (DATA / "python" / "opendgus.py").read_text(encoding="utf-8")
        if mqtt:
            out["secrets.py"] = _secrets_py(project)
    out["README.md"] = readme(project, b, mqtt, main)
    if mqtt:
        out[".gitignore"] = "secrets.h\nsecrets.py\n"
    return out


NEVER_OVERWRITE = ("secrets.h", "secrets.py")


def write(folder: Path, project: Project, board: str, mqtt: bool = False,
          logic: Optional[dict[str, str]] = None) -> dict:
    """Write (or regenerate) <folder>/controller/<board>/. USER CODE blocks already in the files are kept;
    `logic` replaces the blocks it names. secrets files are created once and never overwritten."""
    root = Path(folder) / "controller" / board
    files = generate(project, board, mqtt)
    main = main_file(project, board)
    written, changed = [], []
    for rel, text in files.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        if p.exists() and p.name in NEVER_OVERWRITE:
            continue
        old = p.read_text(encoding="utf-8") if p.exists() else None
        new = fill(text, regions(old) if old else None, logic if rel == main else None)
        if old != new:
            p.write_text(new, encoding="utf-8", newline="\n")
            changed.append(rel)
        written.append(rel)
    return {"folder": str(root), "board": board, "main": main, "files": written, "changed": changed,
            "regions": sorted(regions(files[main]))}
