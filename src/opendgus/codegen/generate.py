REGION = re.compile(r"^[ \t]*(?://|#) USER CODE BEGIN (\S+)[^\n]*\n(.*?)^[ \t]*(?://|#) USER CODE END \1[^\n]*$",
                    re.S | re.M)


@dataclass
class Var:
    name: str
    vp: int
    type: str
    doc: str
    controls: list[str] = field(default_factory=list)     # "toggle 'Kitchen' (page 0)"
    input: bool = False                                    # the display sends it (touch)
    ha: str = "number"                                     # Home Assistant entity kind
    min: int = 0
    max: int = 100

    @property
    def const(self) -> str:
        return "VP_" + self.name.upper()


def variables(project: Project) -> list[Var]:
    vps = project.allocate_vps()
    out = {v.name: Var(v.name, vps[v.name], v.type, v.doc) for v in project.variables}
    for pg in project.pages:
        for c in pg.controls:
            if not c.var or c.var not in out:
                continue
            v = out[c.var]
            label = c.props.get("label") or c.props.get("title") or ""
            v.controls.append(f"{c.type}{' ' + repr(label) if label else ''} (page {pg.id})")
            if c.type.startswith("raw:"):
                from ..formats import spec as S
                spec = S.REGISTRY.get(c.type[4:])
                v.input |= bool(spec and spec.kind == "touch")
                continue
            w = W.WIDGETS.get(c.type)
            if w is not None and w.category == "input":
                v.input = True
                if c.type == "toggle":
                    v.ha, v.max = "switch", 1
                elif c.type == "slider":
                    v.min, v.max = int(c.props.get("min", 0)), int(c.props.get("max", 100))
            elif c.type in ("progress", "slider", "needle"):
                v.min, v.max = int(c.props.get("min", 0)), int(c.props.get("max", 100))
    for v in out.values():
        if v.type == "text":
            v.ha = "text"
        elif not v.input and v.ha == "number":
            v.ha = "sensor"
    return list(out.values())


def sketch_name(project: Project) -> str:
    n = re.sub(r"[^A-Za-z0-9_]+", "_", project.name).strip("_") or "opendgus"
    return ("d_" + n if n[0].isdigit() else n)[:40]


