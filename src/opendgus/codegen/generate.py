def _py_main(project: Project, b: Board, vs: list[Var], mqtt: bool, logic: dict[str, str]) -> str:
    ins = [v for v in vs if v.input]
    outs = [v for v in vs if not v.input]
    L = [f'"""{project.name} - controller for {b.title}.', "",
         "Generated by OpenDGUS: write your code between the USER CODE markers.", "Wiring:"]
    L += [f"    display {d:<10} -> {p}" for d, p in b.wiring] + ['"""']
    L += [b.serial_decl, "", "from dgus_vars import *  # noqa: F401,F403  (VP_*, PAGE_*, DGUS_*, SCREENSAVER_*)",
          "from opendgus import DGUS, sleep_ms"]
    if mqtt:
        L += ["import json", "import secrets"]
        if b.lang == "micropython":
            L += ["import network", "from umqtt.simple import MQTTClient"]
        else:
            L += ["import paho.mqtt.client as paho"]
    L += [""]
    if b.lang == "python":
        L += ['PORT = "/dev/serial0"   # Windows: "COM3", USB adapter on Linux: "/dev/ttyUSB0"']
    L += [b.serial_setup, "dgus = DGUS(uart, crc=bool(DGUS_CRC))", ""]
    if outs:
        L += ["# Variables the controller shows on the display - for example dgus.write(VP_X, value):"]
        L += [f"#   {v.const:<24} {v.type:<6} {', '.join(v.controls) or 'not used on a page'}" for v in outs]
        L += [""]
    L += [_user("globals", logic.get("globals", ""), "", "#").rstrip("\n"), ""]
    if mqtt:
        L += [_mqtt_py(project, vs, b), ""]
    L += ["", "def on_value(vp, value):", '    """Called for every value the display sends (a touch changed a variable)."""']
    if mqtt:
        L += ["    mqtt_publish(vp, value)"]
    first = True
    for v in ins:
        L += [f"    {'if' if first else 'elif'} vp == {v.const}:   # {', '.join(v.controls)}",
              _user(v.const, logic.get(v.const, ""), "        ", "#").rstrip("\n"), "        pass"]
        first = False
    L += [_user("on_value", logic.get("on_value", ""), "    ", "#").rstrip("\n"), "", ""]
    L += ["def setup():", "    sleep_ms(1500)                     # let the display start",
          "    dgus.on_upload(on_value)",
          "    dgus.set_standby(DGUS_STANDBY_ENABLED, DGUS_STANDBY_LEVEL, DGUS_STANDBY_TIMEOUT_S, DGUS_BACKLIGHT)",
          "    if SCREENSAVER_ENABLED:",
          "        dgus.screensaver(SCREENSAVER_PAGE, SCREENSAVER_TIMEOUT_S, SCREENSAVER_WAKE_PAGE, SCREENSAVER_BRIGHTNESS)"]
    if mqtt:
        L += ["    mqtt_setup()"]
    L += [_user("setup", logic.get("setup", ""), "    ", "#").rstrip("\n"), "", "",
          "def loop():", "    dgus.poll()"]
    if mqtt:
        L += ["    mqtt_loop()"]
    L += [_user("loop", logic.get("loop", ""), "    ", "#").rstrip("\n"), "", "",
          "setup()", "while True:", "    loop()", ""]
    return "\n".join(L)


def _mqtt_py(project: Project, vs: list[Var], b: Board) -> str:
    rows = ",\n".join(f'    ({v.const}, "{v.name}", "{_ha_config(v)[0]}", {{{_ha_config(v)[1].replace(":", ": ")}}})'
                      for v in vs if v.type != "text")
    common = f'''# ---- MQTT + Home Assistant discovery (topics: MQTT_PREFIX/<name>/state and /set)
MQTT_VARS = [
{rows}
]
_mqtt = None
_mqtt_retry = 0


def mqtt_publish(vp, value):
    if _mqtt is None:
        return
    for v, name, _, _ in MQTT_VARS:
        if v == vp:
            value = value - 0x10000 if value & 0x8000 else value
            _pub(secrets.MQTT_PREFIX + "/" + name + "/state", str(value))


def _on_set(topic, payload):
    for v, name, _, _ in MQTT_VARS:
        if topic == secrets.MQTT_PREFIX + "/" + name + "/set":
            value = int(float(payload)) & 0xFFFF
            dgus.write(v, value)
            mqtt_publish(v, value)
            on_value(v, value)


def _announce():
    for v, name, comp, extra in MQTT_VARS:
        cfg = {{"name": name, "unique_id": secrets.MQTT_PREFIX + "_" + name,
               "state_topic": secrets.MQTT_PREFIX + "/" + name + "/state",
               "command_topic": secrets.MQTT_PREFIX + "/" + name + "/set",
               "device": {{"identifiers": [secrets.MQTT_PREFIX], "name": secrets.DEVICE_NAME}}}}
        cfg.update(extra)
        _pub("homeassistant/" + comp + "/" + secrets.MQTT_PREFIX + "_" + name + "/config", json.dumps(cfg))
        _sub(secrets.MQTT_PREFIX + "/" + name + "/set")
'''
    if b.lang == "micropython":
        return common + '''

def _pub(topic, payload):
    _mqtt.publish(topic.encode(), payload.encode(), True)


def _sub(topic):
    _mqtt.subscribe(topic.encode())


def mqtt_setup():
    wlan = network.WLAN(network.STA_IF)
    wlan.active(True)
    wlan.connect(secrets.WIFI_SSID, secrets.WIFI_PASSWORD)


def mqtt_loop():
    global _mqtt, _mqtt_retry
    import time
    if _mqtt is None:
        if not network.WLAN(network.STA_IF).isconnected() or time.ticks_diff(time.ticks_ms(), _mqtt_retry) < 5000:
            return
        _mqtt_retry = time.ticks_ms()
        try:
            c = MQTTClient(secrets.MQTT_PREFIX, secrets.MQTT_HOST, secrets.MQTT_PORT, secrets.MQTT_USER,
                           secrets.MQTT_PASSWORD, keepalive=60)
            c.set_callback(lambda t, p: _on_set(t.decode(), p.decode()))
            c.connect()
            _mqtt = c
            _announce()
        except OSError:
            _mqtt = None
        return
    try:
        _mqtt.check_msg()
    except OSError:
        _mqtt = None'''
    return common + '''

def _pub(topic, payload):
    _mqtt.publish(topic, payload, retain=True)


def _sub(topic):
    _mqtt.subscribe(topic)


def mqtt_setup():
    global _mqtt
    c = paho.Client(paho.CallbackAPIVersion.VERSION2, client_id=secrets.MQTT_PREFIX)
    c.username_pw_set(secrets.MQTT_USER, secrets.MQTT_PASSWORD)
    c.on_connect = lambda *a: _announce()
    c.on_message = lambda cl, ud, msg: _on_set(msg.topic, msg.payload.decode())
    c.connect_async(secrets.MQTT_HOST, secrets.MQTT_PORT, 60)
    c.loop_start()
    _mqtt = c


def mqtt_loop():
    pass'''


