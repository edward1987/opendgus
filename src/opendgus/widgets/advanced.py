class ChoiceProps(Props):
    options: list[str] = Field(default_factory=lambda: ["Option 1", "Option 2"], min_length=2, max_length=12)
    color: str = "primary"
    background: str = "surface"
    text_color: str = "text"


@widget
class Choice(Widget):
    key = "choice"
    title = "Choice"
    category = "input"
    doc = "Select one of 2–12 labeled states; the selected option follows the variable."
    needs_var = True
    var_types = ("int16", "uint16")
    verified = "csharp"
    props_model = ChoiceProps

    def _cell(self, ctx, c, label: str, selected: bool, width: int) -> Image.Image:
        p = self.props(c)
        im = Image.new("RGB", (width, c.h), ctx.rgb(p.color if selected else p.background))
        r = ctx.local_renderer()
        r.text(im, (0, 0, width, c.h), label, None, max(10, min(c.h // 3, width // max(3, len(label)))),
               "semibold", "on_primary" if selected else p.text_color, "center", "middle")
        return im

    def draw(self, ctx, c, img, pressed=False):
        p = self.props(c)
        n = len(p.options)
        for i, label in enumerate(p.options):
            x1 = c.x + c.w * i // n
            x2 = c.x + c.w * (i + 1) // n
            img.paste(self._cell(ctx, c, label, i == 0, x2 - x1), (x1, c.y))

    def expand(self, ctx, c):
        p = self.props(c)
        vp = ctx.require_var(c)
        if ctx.var_of(c).type not in self.var_types:
            raise ValueError("choice needs a 16-bit numeric variable")
        n = len(p.options)
        out = []
        for i, label in enumerate(p.options):
            x1 = c.x + c.w * i // n
            x2 = c.x + c.w * (i + 1) // n
            ids = [ctx.icon(self._cell(ctx, c, label, i == value, x2 - x1), dedupe=False)
                   for value in range(n)]
            out.append(Record("return_key", dict(page=ctx.page.id, x1=x1, y1=c.y, x2=x2, y2=c.y+c.h,
                                                  vp=vp, key_code=i)))
            out.append(Record("var_icon", dict(vp=vp, x=x1, y=c.y, v_min=0, v_max=n-1,
                                                icon_min=ids[0], icon_max=ids[-1],
                                                icon_lib=ctx.icon_lib, mode=1)))
        return out


class CurveProps(Props):
    channel: int = Field(0, ge=0, le=7)
    min: int = Field(0, ge=0, le=65535)
    max: int = Field(100, ge=0, le=65535)
    color: str = "primary"
    point_spacing: int = Field(2, ge=1, le=255)


@widget
class Curve(Widget):
    key = "curve"
    title = "Live curve"
    category = "display"
    doc = "Scrolling data from a controller-written DGUS curve channel (0–7)."
    verified = "csharp"
    runtime_input = "controller streams samples to DGUS curve channel"
    props_model = CurveProps

    def draw(self, ctx, c, img, pressed=False):
        p = self.props(c)
        ctx.r.rect(img, (c.x, c.y, c.x+c.w, c.y+c.h), None, stroke=p.color, stroke_width=1)

    def expand(self, ctx, c):
        p = self.props(c)
        if p.max <= p.min:
            raise ValueError("curve max must be greater than min")
        scale = max(1, min(65535, c.h * 256 // (p.max - p.min)))
        return [Record("curve", dict(x1=c.x, y1=c.y, x2=c.x+c.w, y2=c.y+c.h,
                                     y_central=c.y+c.h//2, vd_central=(p.min+p.max)//2,
                                     mul_y=scale, channel=p.channel, dis_hor=p.point_spacing,
                                     color=_rgb565(ctx, p.color)))]
