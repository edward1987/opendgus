"""High-level wrappers around DGUS controls that were previously expert-only."""
from __future__ import annotations

from typing import Literal

from PIL import Image
from pydantic import Field

from .base import Props, Record, Widget, touch_area, widget


def _rgb565(ctx, color: str) -> int:
    r, g, b = ctx.rgb(color)
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


class LiveTextProps(Props):
    color: str = "text"
    font_x: int = Field(12, ge=4, le=64)
    font_y: int = Field(24, ge=8, le=128)
    align: Literal["left", "center", "right"] = "left"


@widget
class LiveText(Widget):
    key = "live_text"
    title = "Live text"
    category = "display"
    doc = "Text written by the controller to a text variable. Uses the display font library."
    needs_var = True
    var_types = ("text",)
    verified = "csharp"
    runtime_input = "controller writes text VP"
    props_model = LiveTextProps

    def expand(self, ctx, c):
        p = self.props(c)
        var = ctx.var_of(c)
        if var.type != "text":
            raise ValueError("live_text needs a text variable")
        return [Record("text_display", dict(vp=ctx.require_var(c), x=c.x, y=c.y, x1=c.x, y1=c.y,
                                            x2=c.x+c.w, y2=c.y+c.h, text_len=var.length,
                                            font_x=p.font_x, font_y=p.font_y,
                                            h_align={"left": 0, "right": 1, "center": 2}[p.align],
                                            color=_rgb565(ctx, p.color)))]


